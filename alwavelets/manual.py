    def current(self):
        """Return (title, lines) of current page."""
        return self.pages[self.page_idx]

    def next_page(self):
        self.page_idx = min(self.page_idx + 1, len(self.pages) - 1)
        self.scroll = 0

    def prev_page(self):
        self.page_idx = max(self.page_idx - 1, 0)
        self.scroll = 0

    def goto(self, idx):
        if 0 <= idx < len(self.pages):
            self.page_idx = idx
            self.scroll = 0

    def scroll_down(self, n=1):
        self.scroll += n

    def scroll_up(self, n=1):
        self.scroll = max(0, self.scroll - n)
